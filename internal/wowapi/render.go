package wowapi

import (
	"regexp"
	"strconv"
	"strings"
)

// declarationFile records compiler origins at the same point as their signatures.
type declarationFile struct {
	lines    []string
	policies map[string]callPolicy
}

func (f *declarationFile) append(lines ...string) {
	for _, line := range lines {
		if strings.ContainsAny(line, "\r\n") {
			reject("declaration must occupy one physical line: " + strconv.Quote(line))
		}
	}
	f.lines = append(f.lines, lines...)
}
func (f *declarationFile) signature(prefix, expression string, policy *callPolicy) {
	f.append(prefix + expression)
	if policy != nil {
		position := strconv.Itoa(len(f.lines)) + ":" + strconv.Itoa(len(prefix)+1)
		f.policies[position] = *policy
	}
}
func (f declarationFile) bytes() []byte { return []byte(strings.Join(f.lines, "\n") + "\n") }

// render consumes only finalized declarations. It cannot discover types, change
// inheritance, or alter the finalized secrecy policy.
func (p declarationProjection) render() map[string][]byte {
	wow := declarationFile{policies: map[string]callPolicy{}}
	wow.append("-- Generated by bin/wow-types generate; DO NOT EDIT.", "-- Canonical native declarations. See docs/api/teal-catalogue.md.", `local type W = require("native_values")`, "local record CatalogueTypes")
	// Preserve the published ordering and source-comment placement using typed
	// passes. Function origins are captured only after their final layout is known.
	for _, declaration := range p.declarations {
		switch declaration.kind {
		case declarationEnum:
			wow.append("   enum " + declaration.name)
			for _, value := range declaration.values {
				wow.append("      " + value)
			}
			wow.append("   end", "")
		case declarationCallback:
			wow.append(aliasLine(declaration), "")
		}
	}
	for _, declaration := range p.declarations {
		wow.append("   -- " + declaration.source)
		switch declaration.kind {
		case declarationEnum, declarationAlias, declarationCallback:
			wow.append("")
		case declarationRecord, declarationInterface:
			word := "record"
			if declaration.kind == declarationInterface {
				word = "interface"
			}
			wow.append("   " + word + " " + declaration.name)
			if len(declaration.bases) > 0 {
				wow.append("      is " + strings.Join(declaration.bases, ", "))
			}
			for _, field := range declaration.fields {
				wow.append("      " + field.name + ": " + field.expression)
			}
			for _, method := range declaration.methods {
				if method.restrictions != "" {
					wow.append("      -- " + method.restrictions)
				}
				for _, signature := range method.signatures {
					wow.signature("      "+method.name+": ", signature.expression, signature.policy)
				}
			}
			wow.append("   end", "")
		}
	}
	for _, declaration := range p.declarations {
		if declaration.kind == declarationAlias {
			wow.append(aliasLine(declaration), "")
		}
	}
	for _, global := range p.globals {
		wow.signature("   type Global_"+ident(global.name)+" = ", global.expression, global.policy)
	}
	for _, name := range nativeValueExports {
		wow.append("   type " + name + nativeValueParameters[name] + " = W." + name + nativeValueParameters[name])
	}
	wow.append("end", "", "return CatalogueTypes")
	files := map[string][]byte{"wow.d.tl": wow.bytes()}
	locations := map[string]map[string]callPolicy{"types/wow/wow.d.tl": wow.policies}
	for _, name := range []string{"wow_env.d.tl", "wow_secure_env.d.tl"} {
		env := declarationFile{policies: map[string]callPolicy{}}
		env.append("-- Generated public native environment; addon fragments add only owned globals.", `local type W = require("wow")`)
		for _, global := range p.globals {
			if global.public {
				env.signature("global "+global.name+": ", global.ambientExpression, global.policy)
			}
		}
		if name == "wow_secure_env.d.tl" {
			env.append("-- Additional globals exist only in Blizzard's secure environment.")
			for _, global := range p.secureGlobals {
				env.append("global " + global + ": W.Global_" + ident(global))
			}
		}
		files[name] = env.bytes()
		locations["types/wow/"+name] = env.policies
	}
	files["call_policy.lua"] = renderCallPolicy(locations)
	return files
}

func aliasLine(declaration projectedDeclaration) string {
	parameters := ""
	if len(declaration.generics) > 0 {
		parameters = "<" + strings.Join(declaration.generics, ", ") + ">"
	}
	return "   type " + declaration.name + parameters + " = " + declaration.expression
}

// nativeValueExports are the native_values.d.tl types re-exported by wow, so
// generated environment files and addons name them through the wow module.
var nativeValueExports = []string{"Data", "Atom", "SecretData", "SecretTable", "MaybeSecret", "Secret"}

var nativeValueParameters = map[string]string{"MaybeSecret": "<T>", "Secret": "<T>"}

var qualifyName = regexp.MustCompile(`[A-Za-z_]\w*`)

func qualifyExports(text string, exports map[string]bool) string {
	var out strings.Builder
	last := 0
	for _, index := range qualifyName.FindAllStringIndex(text, -1) {
		start, end := index[0], index[1]
		out.WriteString(text[last:start])
		name := text[start:end]
		preceded := false
		if start > 0 {
			ch := text[start-1]
			preceded = ch == '.' || ch == '_' || ch >= 'a' && ch <= 'z' || ch >= 'A' && ch <= 'Z' || ch >= '0' && ch <= '9'
		}
		if !preceded && exports[name] {
			out.WriteString("W.")
		}
		out.WriteString(name)
		last = end
	}
	out.WriteString(text[last:])
	return out.String()
}
