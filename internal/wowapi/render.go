package wowapi

import (
	"regexp"
	"strings"
)

// render consumes only finalized declarations. It cannot discover types, change
// inheritance, or alter the finalized secrecy policy.
func (p declarationProjection) render() map[string][]byte {
	lines := []string{"-- Generated by scripts/wow_api/generate.py; DO NOT EDIT.", "-- Canonical native declarations. See docs/api/teal-catalogue.md.", `local type W = require("native_values")`, "local record OpaqueValue", "   is userdata", "end", ""}
	for _, declaration := range p.declarations {
		if declaration.name == "OpaqueValue" {
			continue
		}
		lines = append(lines, "-- "+declaration.source)
		switch declaration.kind {
		case declarationExternal:
		case declarationEnum:
			lines = append(lines, "local enum "+declaration.name)
			for _, value := range declaration.values {
				lines = append(lines, "   "+value)
			}
			lines = append(lines, "end", "")
		case declarationAlias, declarationCallback:
			parameters := ""
			if len(declaration.generics) > 0 {
				parameters = "<" + strings.Join(declaration.generics, ", ") + ">"
			}
			lines = append(lines, "local type "+declaration.name+parameters+" = "+declaration.expression, "")
		case declarationRecord, declarationInterface:
			word := "record"
			if declaration.kind == declarationInterface {
				word = "interface"
			}
			lines = append(lines, "local "+word+" "+declaration.name)
			if len(declaration.bases) > 0 {
				lines = append(lines, "   is "+strings.Join(declaration.bases, ", "))
			}
			for _, field := range declaration.fields {
				lines = append(lines, "   "+field.name+": "+field.expression)
			}
			for _, method := range declaration.methods {
				if method.restrictions != "" {
					lines = append(lines, "   -- "+method.restrictions)
				}
				for _, signature := range method.signatures {
					lines = append(lines, "   "+method.name+": "+signature.expression)
				}
			}
			lines = append(lines, "end", "")
		}
	}
	env := []string{"-- Generated public native environment; addon fragments add only owned globals.", `local type W = require("wow")`, "local type CatalogueTable = {unknown: unknown}"}
	for _, global := range p.globals {
		if global.public {
			env = append(env, "global "+global.name+": "+global.ambientExpression)
		}
	}
	// This ordering and comment placement are part of the reviewed byte contract.
	header := append([]string{}, lines[:3]...)
	body := lines[3:]
	enumLines, aliasLines, ordinary := []string{}, []string{}, []string{}
	for index := 0; index < len(body); {
		line := body[index]
		switch {
		case strings.HasPrefix(line, "local type Callback_"):
			enumLines = append(enumLines, line, "")
			index++
		case strings.HasPrefix(line, "local type "):
			aliasLines = append(aliasLines, line, "")
			index++
		case strings.HasPrefix(line, "local enum "):
			end := index + 1
			for body[end] != "end" {
				end++
			}
			enumLines = append(enumLines, body[index:end+1]...)
			enumLines = append(enumLines, "")
			index = end + 1
		default:
			ordinary = append(ordinary, line)
			index++
		}
	}
	body = append(append(enumLines, ordinary...), aliasLines...)
	lines = append(header, "local type CatalogueTable = {unknown: unknown}", "local record CatalogueTypes")
	for _, line := range body {
		if line != "" {
			lines = append(lines, "   "+strings.TrimPrefix(line, "local "))
		} else {
			lines = append(lines, "")
		}
	}
	for _, global := range p.globals {
		lines = append(lines, "   type Global_"+ident(global.name)+" = "+global.expression)
	}
	for _, name := range []string{"OpaqueNumber", "OpaqueText", "NumberLike", "TextLike"} {
		lines = append(lines, "   type "+name+" = W."+name)
	}
	lines = append(lines, "end", "", "return CatalogueTypes", "")
	secureEnv := append(append([]string{}, env...), "-- Additional globals exist only in Blizzard's secure environment.")
	for _, name := range p.secureGlobals {
		secureEnv = append(secureEnv, "global "+name+": W.Global_"+ident(name))
	}
	files := map[string][]byte{"wow.d.tl": []byte(strings.Join(lines, "\n")), "wow_env.d.tl": []byte(strings.Join(env, "\n") + "\n"), "wow_secure_env.d.tl": []byte(strings.Join(secureEnv, "\n") + "\n")}
	files["call_policy.lua"] = p.renderCallPolicy(files)
	return files
}

var qualifyName = regexp.MustCompile(`[A-Za-z_]\w*`)

func qualifyExports(text string, exports map[string]bool) string {
	var out strings.Builder
	last := 0
	for _, index := range qualifyName.FindAllStringIndex(text, -1) {
		start, end := index[0], index[1]
		out.WriteString(text[last:start])
		name := text[start:end]
		preceded := false
		if start > 0 {
			ch := text[start-1]
			preceded = ch == '.' || ch == '_' || ch >= 'a' && ch <= 'z' || ch >= 'A' && ch <= 'Z' || ch >= '0' && ch <= '9'
		}
		if !preceded && exports[name] {
			out.WriteString("W.")
		}
		out.WriteString(name)
		last = end
	}
	out.WriteString(text[last:])
	return out.String()
}
